import unittest,math,sys,pathlib,csv,json
ROOT=pathlib.Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'src'))
from rice_response import *
class Tests(unittest.TestCase):
 @classmethod
 def setUpClass(cls):cls.res,cls.sals,cls.spectra,cls.legs=run(ROOT)
 def test_rows(self):self.assertEqual(len(self.sals),12)
 def test_legs(self):self.assertEqual(len(self.legs),10)
 def test_low_point(self):self.assertAlmostEqual(self.sals[0]['reconstructed_1998_nb_sr'],.635,delta=.002)
 def test_high_point(self):self.assertAlmostEqual(self.sals[6]['reconstructed_1998_nb_sr'],.118,delta=.002)
 def test_stat(self):self.assertAlmostEqual(self.sals[0]['reconstructed_stat_sd_nb_sr'],.123,delta=.002)
 def test_all_dsigmas_within_printed(self):self.assertLess(max(abs(x['reconstructed_1998_nb_sr']-x['thesis_1998_nb_sr']) for x in self.sals),.007)
 def test_all_stats_within_printed(self):self.assertLess(max(abs(x['reconstructed_stat_sd_nb_sr']-x['thesis_stat_sd_nb_sr']) for x in self.sals if not x['stat_error_internal_source_mismatch']),.003)
 def test_lab_cm(self):self.assertLess(max(abs(x['lab_theta_SR_exact_deg']-x['lab_theta_deg']) for x in self.sals),.25)
 def test_jacobian_all(self):self.assertLess(max(abs(x['J_SR_exact']-x['J_thesis']) for x in self.sals),.005)
 def test_j_170(self):self.assertAlmostEqual(kinematics(170,44.7)['J_calculated'],.7902328422698132,delta=1e-10)
 def test_j_220(self):self.assertAlmostEqual(kinematics(220,63.6)['J_calculated'],.8278041383840767,delta=1e-10)
 def test_j_threshold_reject(self):
  with self.assertRaises(ValueError):kinematics(20,60)
 def test_k_energy_sum(self):self.assertAlmostEqual(kinematics(170,90)['pair_sum_K_MeV'],170+M_ALPHA_MEV-2*M_D_MEV,delta=1e-12)
 def test_schiff_positive(self):self.assertTrue(all(schiff_shape(x)>0 for x in (150,170,190,220,250)))
 def test_schiff_zero_at_endpoint(self):self.assertEqual(schiff_shape(273.),0.)
 def test_schiff_simpson(self):self.assertAlmostEqual(simpson(schiff_shape,150,190,6000),simpson(schiff_shape,150,190,12000),delta=1e-8)
 def test_schiff_low(self):self.assertAlmostEqual(self.spectra[0]['ratio_to_tagged_171_212'],1.1162284145921444,delta=1e-8)
 def test_schiff_high(self):self.assertAlmostEqual(self.spectra[1]['ratio_to_tagged_171_212'],1.2575051038919696,delta=1e-8)
 def test_schiff_high_source_disagreement(self):self.assertGreater(abs(self.spectra[1]['author_ratio']-self.spectra[1]['ratio_to_tagged_171_212']),.25)
 def test_anomaly_not_rescaled(self):self.assertAlmostEqual(self.sals[7]['thesis_1998_nb_sr'],.486)
 def test_published_last(self):self.assertAlmostEqual(self.sals[-1]['published_2000_nb_sr'],.43)
 def test_published_status(self):self.assertTrue(all('same_experiment' in x['source_status'] for x in self.sals))
 def test_stat_source_anomaly(self):self.assertEqual(sum(x['stat_error_internal_source_mismatch'] for x in self.sals),1);self.assertAlmostEqual(self.sals[5]['reconstructed_stat_sd_nb_sr'],.14042136,delta=1e-8)
 def test_legs_counts_total(self):self.assertEqual(sum(x['raw_counts_parallel']+x['raw_counts_perpendicular'] for x in self.legs),395)
 def test_legs_ratio(self):self.assertAlmostEqual(self.legs[0]['flux_corrected_raw_asymmetry'],.3303438,delta=1e-7)
 def test_legs_bounded(self):self.assertTrue(all(abs(x['flux_corrected_raw_asymmetry'])<1 for x in self.legs))
 def test_double_symmetry(self):self.assertAlmostEqual(kinematics(170,60)['pair_sum_K_MeV'],kinematics(170,120)['pair_sum_K_MeV'])
 def test_zero_not_promoted(self):self.assertIsNone(self.res['R_event']);self.assertEqual(self.res['PRODUCTION'],'HOLD');self.assertFalse(self.res['L4'])
if __name__=='__main__':unittest.main()
